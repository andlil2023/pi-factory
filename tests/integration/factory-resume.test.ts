import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import type { FactoryRunState } from '../../src/state-store.ts';

const cli = resolve('src/factory-cli.ts');
for (const budget of [undefined, 2] as const) test(`CLI pins ${budget === undefined ? 'default' : 'explicit'} infrastructure budget and resumes with history intact`, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'factory-resume-cli-'));
  const repository = join(dir, 'project');
  // The CLI chooses its default sibling .factory-worktrees directory inside this fixture.
  t.after(() => rm(dir, { recursive: true, force: true }));
  await mkdir(repository);
  const git = (...args: string[]) => execFileSync('git', args, { cwd: repository, encoding: 'utf8' }).trim();
  git('init');
  git('config', 'user.name', 'Test');
  git('config', 'user.email', 'test@example.invalid');
  git('config', 'core.autocrlf', 'false');
  await writeFile(join(repository, '.gitignore'), '.factory/\n');
  git('add', '.');
  git('commit', '-m', 'initial');
  const originalHead = git('rev-parse', 'HEAD');
  const tasks = ['T001', 'T002'].map((id, index) => ({ id, title: `Task ${id}`, objective: 'Write a fixture file', scope: `${id}.txt`, acceptanceCriteria: ['Fixture file exists'], dependencies: index ? ['T001'] : [], verification: ['trusted-check'] }));
  const plan = join(dir, 'plan.json');
  await writeFile(plan, JSON.stringify({ objective: 'Fixture', assumptions: [], decisions: [], tasks, verification: ['trusted-check'] }));
  const config = join(dir, 'config.json');
  const model = { provider: 'fixture', model: 'fixture' };
  const settings = { agents: { planner: model, implementer: model, reviewer: model }, setup: [{ executable: process.execPath, args: ['-e', "require('fs').mkdirSync('.factory', {recursive:true}); require('fs').writeFileSync('.factory/setup-marker', 'ready')"] }], execution: { maxAttempts: 3, ...(budget === undefined ? {} : { maxInfraRetries: budget }) }, verification: [{ executable: process.execPath, args: ['-e', 'process.exit(0)'] }], pi: { executable: process.execPath, executableArgs: [resolve('tests/fixtures/fake-factory-agent.mjs')] } };
  await writeFile(config, JSON.stringify(settings));
  const runCli = (...args: string[]) => spawnSync(process.execPath, ['--experimental-strip-types', cli, ...args, '--config', config], { encoding: 'utf8', timeout: 180_000 });
  for (const invalid of [-1, 0.5, Number.MAX_SAFE_INTEGER + 1, '1', null]) {
    await writeFile(config, JSON.stringify({ ...settings, execution: { maxAttempts: 3, maxInfraRetries: invalid } }));
    const rejected = runCli('run', '--repo', repository, '--plan', plan, '--approve');
    assert.notEqual(rejected.status, 0);
    assert.match(rejected.stderr, /Invalid execution.maxInfraRetries/);
  }
  await writeFile(config, JSON.stringify(settings));
  const first = runCli('run', '--repo', repository, '--plan', plan, '--approve');
  assert.equal(first.status, 1, first.stdout + first.stderr);
  const directory = join(repository, '.factory', 'runs');
  const file = (await readdir(directory)).find(file => file.endsWith('.json') && !file.endsWith('.jsonl'))!;
  assert.ok(file, first.stdout + first.stderr);
  const statePath = join(directory, file);
  const blocked = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  const worktree = blocked.git!.worktree;
  assert.equal(await readFile(join(worktree, '.factory', 'setup-marker'), 'utf8'), 'ready');
  assert.equal(blocked.specification, undefined);
  assert.equal(blocked.status, 'blocked');
  assert.equal(blocked.tasks.T001.attempts.length, 1);
  assert.equal(blocked.tasks.T001.status, 'completed');
  assert.equal(blocked.tasks.T002.status, 'blocked');
  assert.equal(blocked.git!.expectedHead, blocked.tasks.T001.checkpointCommit);
  assert.equal(blocked.execution?.maxAttempts, 3);
  assert.equal(blocked.execution?.maxInfraRetries, budget ?? 1);
  await writeFile(config, JSON.stringify({ ...settings, execution: { maxAttempts: 3, maxInfraRetries: 0 } }));
  const mismatch = runCli('resume', '--repo', repository, '--run', blocked.runId, '--retry-task', 'T002', '--approve');
  assert.notEqual(mismatch.status, 0);
  assert.match(mismatch.stderr, /original execution configuration/);
  const selection = { rules: [{ path: 'T002.txt', commands: [0] }], dependencyPaths: [], dependenciesComprehensive: true };
  await writeFile(config, JSON.stringify({ ...settings, verificationSelection: selection }));
  const selectionMismatch = runCli('resume', '--repo', repository, '--run', blocked.runId, '--retry-task', 'T002', '--approve');
  assert.notEqual(selectionMismatch.status, 0);
  assert.match(selectionMismatch.stderr, /original execution configuration/);
  await writeFile(config, JSON.stringify(settings));
  const acceptedWork = await readFile(join(worktree, 'T001.txt'), 'utf8');
  const failedWork = await readFile(join(worktree, 'T002.txt'), 'utf8');
  const unapproved = runCli('resume', '--repo', repository, '--run', blocked.runId);
  assert.equal(unapproved.status, 1);
  assert.match(unapproved.stderr, /requires --approve/);
  const implicitRetry = runCli('resume', '--repo', repository, '--run', blocked.runId, '--approve');
  assert.equal(implicitRetry.status, 1);
  assert.match(implicitRetry.stderr, /--retry-task T002/);
  assert.equal(await readFile(join(worktree, 'T002.txt'), 'utf8'), failedWork);
  const guidance = join(dir, 'guidance.txt');
  await writeFile(guidance, 'Operator says proceed.');
  const resumed = runCli('resume', '--repo', repository, '--run', blocked.runId, '--retry-task', 'T002', '--guidance', guidance, '--approve');
  assert.equal(resumed.status, 0, resumed.stdout + resumed.stderr);
  const completed = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  assert.equal(completed.status, 'completed');
  assert.equal(completed.git?.worktree, worktree);
  assert.equal(completed.tasks.T001.attempts.length, 1);
  assert.equal(await readFile(join(worktree, 'T001.txt'), 'utf8'), acceptedWork);
  assert.equal(completed.tasks.T002.attempts[0].outcome, 'blocked');
  assert.equal(completed.tasks.T002.attempts.length, 2);
  assert.equal(completed.resumptions?.length, 1);
  assert.equal(completed.resumptions![0].guidance, 'Operator says proceed.');
  assert.equal(completed.git?.expectedHead, completed.tasks.T002.checkpointCommit);
  assert.equal(completed.execution?.maxAttempts, 3);
  assert.equal(git('rev-parse', 'HEAD'), originalHead);
  assert.equal(git('status', '--porcelain'), '');
  assert.equal((await readdir(dirname(worktree))).length, 1);
  const events = (await readFile(join(directory, `${blocked.runId}.events.jsonl`), 'utf8')).trim().split('\n').map(line => JSON.parse(line) as { type: string });
  assert.equal(events.filter(event => event.type === 'RUN_STARTED').length, 2);
  assert.ok(events.some(event => event.type === 'RUN_COMPLETED'));
  const again = runCli('resume', '--repo', repository, '--run', blocked.runId, '--approve');
  assert.equal(again.status, 1);
  assert.match(again.stderr, /already completed/);
  const unapprovedIntegration = runCli('integrate', '--repo', repository, '--run', blocked.runId);
  assert.equal(unapprovedIntegration.status, 1);
  assert.match(unapprovedIntegration.stderr, /requires --approve/);
  await writeFile(config, JSON.stringify({ ...settings, verificationSelection: selection }));
  const integrationMismatch = runCli('integrate', '--repo', repository, '--run', blocked.runId, '--approve');
  assert.notEqual(integrationMismatch.status, 0);
  assert.match(integrationMismatch.stderr, /original execution configuration/);
  await writeFile(config, JSON.stringify(settings));
  const prepared = runCli('integrate', '--repo', repository, '--run', blocked.runId, '--approve');
  assert.equal(prepared.status, 0, prepared.stdout + prepared.stderr);
  const ready = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  const candidate = ready.integrations!.at(-1)!;
  assert.equal(candidate.status, 'ready');
  assert.equal(git('rev-parse', 'HEAD'), originalHead);
  const unapprovedPublication = runCli('integrate', '--repo', repository, '--run', blocked.runId, '--publish', '--candidate', candidate.commit!);
  assert.equal(unapprovedPublication.status, 1);
  assert.match(unapprovedPublication.stderr, /requires --approve/);
  const wrongCandidate = runCli('integrate', '--repo', repository, '--run', blocked.runId, '--publish', '--candidate', 'wrong', '--approve');
  assert.equal(wrongCandidate.status, 1);
  assert.equal(git('rev-parse', 'HEAD'), originalHead);
  const published = runCli('integrate', '--repo', repository, '--run', blocked.runId, '--publish', '--candidate', candidate.commit!, '--approve');
  assert.equal(published.status, 0, published.stdout + published.stderr);
  const integrated = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  assert.equal(integrated.integrations!.at(-1)!.status, 'published');
  assert.equal(git('rev-parse', 'HEAD'), candidate.commit);
  assert.equal(integrated.git!.expectedHead, completed.git!.expectedHead);
});
