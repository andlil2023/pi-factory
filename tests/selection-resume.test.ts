import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import type { FactoryRunState } from '../src/state-store.ts';

test('resumed repair selects cumulative changes since the last accepted checkpoint and pins selection configuration', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'selection-resume-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const repo = join(dir, 'repo'); await mkdir(repo);
  const git = (...args: string[]) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();
  git('init'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  await writeFile(join(repo, '.gitignore'), '.factory/\n'); git('add', '.'); git('commit', '-m', 'initial');
  const tasks = ['T001', 'T002'].map((id, index) => ({ id, title: id, objective: 'fixture', scope: 'fixture', acceptanceCriteria: ['fixture'], dependencies: index ? ['T001'] : [], verification: ['fixture'] }));
  const plan = join(dir, 'plan.json'); await writeFile(plan, JSON.stringify({ objective: 'fixture', assumptions: [], decisions: [], tasks, verification: ['fixture'] }));
  const config = join(dir, 'config.json');
  const model = { provider: 'fixture', model: 'fixture' };
  const selection = { rules: [{ path: 'accepted.txt', commands: [2] }, { path: 'first.txt', commands: [0] }, { path: 'repair.txt', commands: [1] }], dependencyPaths: [], dependenciesComprehensive: true };
  const settings = { agents: { planner: model, implementer: model, reviewer: model }, execution: { maxAttempts: 3 }, verification: [0, 1, 2].map(n => ({ executable: process.execPath, args: ['-e', `console.log(${n})`] })), verificationSelection: selection, pi: { executable: process.execPath, executableArgs: [resolve('tests/fixtures/fake-resume-selection-agent.mjs')] } };
  await writeFile(config, JSON.stringify(settings));
  const cli = (...args: string[]) => spawnSync(process.execPath, ['--experimental-strip-types', resolve('src/factory-cli.ts'), ...args, '--config', config], { encoding: 'utf8', timeout: 60_000 });
  const first = cli('run', '--repo', repo, '--plan', plan, '--approve'); assert.equal(first.status, 1, first.stdout + first.stderr);
  const runs = join(repo, '.factory', 'runs'); const file = (await readdir(runs)).find(name => name.endsWith('.json'))!;
  const statePath = join(runs, file); const blocked = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  assert.equal(blocked.tasks.T001.status, 'completed'); assert.equal(blocked.tasks.T002.status, 'blocked');
  assert.equal(blocked.git!.expectedHead, blocked.tasks.T001.checkpointCommit);
  const changed = { ...settings, verificationSelection: { ...selection, rules: selection.rules.map(rule => rule.path === 'first.txt' ? { ...rule, commands: [1] } : rule) } };
  await writeFile(config, JSON.stringify(changed));
  const rejected = cli('resume', '--repo', repo, '--run', blocked.runId, '--retry-task', 'T002', '--approve');
  assert.notEqual(rejected.status, 0); assert.match(rejected.stderr, /original execution configuration/);
  await writeFile(config, JSON.stringify(settings));
  const resumed = cli('resume', '--repo', repo, '--run', blocked.runId, '--retry-task', 'T002', '--approve');
  assert.equal(resumed.status, 0, resumed.stdout + resumed.stderr);
  const completed = JSON.parse(await readFile(statePath, 'utf8')) as FactoryRunState;
  const verification = completed.tasks.T002.attempts[1].verification as { details: { mode: string; evidence: { changes: { path: string }[] }; checks: { stdout: string; passed: boolean }[] } };
  const details = verification.details;
  assert.equal(details.mode, 'selected');
  assert.deepEqual(details.evidence.changes.map(c => c.path).sort(), ['first.txt', 'repair.txt']);
  assert.deepEqual(details.checks.map(check => [check.stdout.trim(), check.passed]), [['0', true], ['1', true]]);
  await writeFile(config, JSON.stringify(changed));
  const integration = cli('integrate', '--repo', repo, '--run', blocked.runId, '--approve');
  assert.notEqual(integration.status, 0); assert.match(integration.stderr, /original execution configuration/);
});
